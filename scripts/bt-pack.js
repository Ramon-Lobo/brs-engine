#!/usr/bin/env node
/*
 * bt-pack: build a brighttest patched tarball of brs-node from a `bt/<upstream-version>` queue branch.
 *
 * The source tree keeps the upstream package name (`brs-node`) so upstream's own tests keep resolving.
 * Everything brighttest-specific happens here, at pack time, in a staging directory:
 *   - package name -> @ramonlobo/brs-node, version -> <upstream>-bt.<N>
 *   - the SceneGraph bundle's webpack external `require("brs-node")` -> `require("@ramonlobo/brs-node")`
 *   - a `brighttest` stamp in package.json (patch ids and revisions, local-only "nonDevice" list)
 *   - BT-PATCHES.md generated from the queue's commit trailers (BT-Patch, Upstream, Device-verified, Non-device)
 *
 * Usage: node scripts/bt-pack.js --build <N> [--base <tag>] [--out <dir>] [--skip-build]
 *   --build N     brighttest build number, produces <upstream>-bt.<N>   (required)
 *   --base TAG    upstream tag the queue sits on (default: v<package version>)
 *   --out DIR     output directory for the staging folder and the .tgz  (default: ./out/bt-pack)
 *   --skip-build  reuse the existing packages/node/bin (default: clean + production build + SG build)
 *   --dry-run     do everything except `npm pack`
 *
 * Never publishes. Publishing is a manual, owner-only step.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const SCOPED_NAME = "@ramonlobo/brs-node";
const STOCK_NAME = "brs-node";
const root = path.resolve(__dirname, "..");
const nodePkgDir = path.join(root, "packages", "node");

function parseArgs(argv) {
    const args = { build: null, base: null, out: path.join(root, "out", "bt-pack"), skipBuild: false, dryRun: false };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === "--build") args.build = argv[++i];
        else if (a === "--base") args.base = argv[++i];
        else if (a === "--out") args.out = path.resolve(argv[++i]);
        else if (a === "--skip-build") args.skipBuild = true;
        else if (a === "--dry-run") args.dryRun = true;
        else throw new Error(`unknown argument: ${a}`);
    }
    if (!/^[1-9]\d*$/.test(String(args.build))) throw new Error("--build <N> (positive integer) is required");
    return args;
}

function run(cmd, args, opts = {}) {
    return execFileSync(cmd, args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], ...opts });
}

function git(...args) {
    return run("git", args).trim();
}

function readQueue(base) {
    // oldest first; %x1e separates records, %x1f separates the sha, subject and trailers
    const raw = run("git", ["log", "--reverse", `--format=%H%x1f%s%x1f%(trailers:only,unfold)%x1e`, `${base}..HEAD`]);
    return raw
        .split("\x1e")
        .map((r) => r.trim())
        .filter(Boolean)
        .map((r) => {
            const [sha, subject, trailerText] = r.split("\x1f");
            const trailers = {};
            for (const line of (trailerText || "").split("\n")) {
                const m = /^([A-Za-z-]+):\s*(.*)$/.exec(line.trim());
                if (m) trailers[m[1]] = m[2];
            }
            return { sha, subject, trailers };
        })
        .filter((c) => c.trailers["BT-Patch"]);
}

function patchRevision(sha) {
    // revision bumps when a patch's behavior changes; the queue starts every patch at 1
    return 1;
}

function renderPatchesDoc(info, queue, baseTag) {
    const lines = [
        `# brighttest patches on ${info.upstream}`,
        "",
        `Build \`${info.build}\` of \`${SCOPED_NAME}\`, queue \`${info.queue}\` on upstream tag \`${baseTag}\`.`,
        "This file is generated by `scripts/bt-pack.js` from the commit trailers of the queue.",
        "",
        "| Patch | Commit | Upstream | Device-verified | Non-device | Subject |",
        "|---|---|---|---|---|---|",
    ];
    for (const c of queue) {
        const t = c.trailers;
        lines.push(
            `| ${t["BT-Patch"]} | ${c.sha.slice(0, 8)} | ${t["Upstream"] || ""} | ${t["Device-verified"] || ""} | ${
                t["Non-device"] || ""
            } | ${c.subject} |`
        );
    }
    lines.push(
        "",
        "Behavior marked Non-device does not exist on a real Roku (brighttest convenience, never upstreamed).",
        ""
    );
    return lines.join("\n");
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    const nodePkg = JSON.parse(fs.readFileSync(path.join(nodePkgDir, "package.json"), "utf8"));
    if (nodePkg.name !== STOCK_NAME) {
        throw new Error(`source package name is ${nodePkg.name}, expected ${STOCK_NAME} (no source rename)`);
    }
    const upstreamVersion = nodePkg.version;
    const baseTag = args.base || `v${upstreamVersion}`;
    const branch = git("rev-parse", "--abbrev-ref", "HEAD");
    if (git("status", "--porcelain", "--untracked-files=no")) {
        throw new Error("working tree has uncommitted changes to tracked files; commit or stash first");
    }

    const queue = readQueue(baseTag);
    const featurePatches = queue.filter((c) => c.trailers["BT-Patch"] !== "BRS-90");
    const stamp = {
        upstream: `${STOCK_NAME}@${upstreamVersion}`,
        queue: branch,
        build: `v${upstreamVersion}-bt.${args.build}`,
        patches: Object.fromEntries(featurePatches.map((c) => [c.trailers["BT-Patch"], patchRevision(c.sha)])),
        nonDevice: featurePatches
            .filter((c) => /^yes$/i.test(c.trailers["Non-device"] || ""))
            .map((c) => c.trailers["BT-Patch"]),
    };

    if (!args.skipBuild) {
        run("npm", ["run", "clean", "-w", STOCK_NAME], { stdio: "inherit" });
        run("npm", ["run", "release", "-w", STOCK_NAME], { stdio: "inherit" });
        run("npm", ["run", "build:sg", "-w", STOCK_NAME], { stdio: "inherit" });
    }

    const stage = path.join(args.out, "stage");
    fs.rmSync(stage, { recursive: true, force: true });
    fs.mkdirSync(stage, { recursive: true });

    // copy what the stock package ships (packages/node/package.json "files"), plus LICENSE and CHANGELOG
    for (const entry of ["bin", "assets", path.join("types", "src", "core")]) {
        const from = path.join(nodePkgDir, entry);
        if (!fs.existsSync(from))
            throw new Error(`missing build output: ${path.relative(root, from)} (run without --skip-build)`);
        fs.cpSync(from, path.join(stage, entry), { recursive: true });
    }
    fs.copyFileSync(path.join(root, "CHANGELOG.md"), path.join(stage, "CHANGELOG.md"));
    fs.copyFileSync(path.join(root, "LICENSE"), path.join(stage, "LICENSE"));

    // SG bundle: point the webpack external at the scoped package
    const sgFile = path.join(stage, "bin", "brs-sg.node.js");
    const sgSource = fs.readFileSync(sgFile, "utf8");
    const from = `require("${STOCK_NAME}")`;
    const occurrences = sgSource.split(from).length - 1;
    if (occurrences !== 1) {
        throw new Error(`expected exactly one ${from} in brs-sg.node.js, found ${occurrences}`);
    }
    fs.writeFileSync(sgFile, sgSource.replace(from, `require("${SCOPED_NAME}")`));

    // package.json: scoped name, bt version, files, stamp
    const pkg = { ...nodePkg };
    pkg.name = SCOPED_NAME;
    pkg.version = `${upstreamVersion}-bt.${args.build}`;
    pkg.files = [...new Set([...(nodePkg.files || []), "LICENSE", "BT-PATCHES.md"])];
    delete pkg.scripts;
    delete pkg.devDependencies;
    pkg.brighttest = stamp;
    fs.writeFileSync(path.join(stage, "package.json"), JSON.stringify(pkg, null, 2) + "\n");

    fs.writeFileSync(path.join(stage, "BT-PATCHES.md"), renderPatchesDoc(stamp, queue, baseTag));

    if (args.dryRun) {
        console.log(`dry run: staged ${path.relative(root, stage)} (${pkg.name}@${pkg.version}), stamp:`);
        console.log(JSON.stringify(stamp, null, 2));
        return;
    }
    const out = execFileSync("npm", ["pack", "--pack-destination", args.out, "--json", "--ignore-scripts"], {
        cwd: stage,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "inherit"],
    });
    const info = JSON.parse(out)[0];
    console.log(`packed ${path.join(args.out, info.filename)} (${info.entryCount} files, ${info.size} bytes)`);
    console.log(JSON.stringify(stamp, null, 2));
}

try {
    main();
} catch (err) {
    console.error(`bt-pack: ${err.message}`);
    process.exit(1);
}
